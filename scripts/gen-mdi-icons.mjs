// 一次性脚本：从 @mdi/js 生成 server/internal/icons/mdi_paths.go
// 用法：node scripts/gen-mdi-icons.mjs   （首次会自动 npm install --no-save @mdi/js 到临时目录）
import { createRequire } from 'module'
import { writeFileSync, mkdirSync, rmSync, existsSync } from 'fs'
import { execSync } from 'child_process'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const tmp = join(root, 'node_modules', '.tmp-mdi')
mkdirSync(tmp, { recursive: true })
if (!existsSync(join(tmp, 'node_modules', '@mdi', 'js', 'mdi.js'))) {
  execSync('npm install --no-save --prefix ' + JSON.stringify(tmp) + ' @mdi/js', { stdio: 'inherit' })
}
const require = createRequire(join(tmp, 'x.js'))
const { default: paths } = await import(join(tmp, 'node_modules', '@mdi', 'js', 'mdi.js')).then(m => ({ default: m.default ?? m })).catch(async () => {
  // ESM 直读失败时退回 require
  return { default: require(join(tmp, 'node_modules', '@mdi', 'js', 'mdi.js')) }
})

const entries = Object.entries(paths)
  .filter(([k, v]) => /^mdi[A-Z]/.test(k) && typeof v === 'string')
  .map(([k, v]) => {
    // mdiRobotVacuum -> robot-vacuum
    const name = k.replace(/^mdi/, '').replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
    return { name, d: v }
  })
  .sort((a, b) => a.name.localeCompare(b.name))

let out = '// Code generated by scripts/gen-mdi-icons.mjs; DO NOT EDIT.\n'
out += '// MDI (Material Design Icons) path data, Apache-2.0 license.\n'
out += 'package icons\n\n'
out += '// mdiPaths 以 mdi 短名（连字符，如 robot-vacuum）为键，值为 SVG path 的 d 属性。\n'
out += 'var mdiPaths = map[string]string{\n'
for (const { name, d } of entries) {
  out += '\t' + JSON.stringify(name) + ': ' + JSON.stringify(d) + ',\n'
}
out += '}\n'

const dst = join(root, 'server', 'internal', 'icons', 'mdi_paths.go')
writeFileSync(dst, out)
console.log('written', dst, entries.length, 'icons,', (out.length / 1048576).toFixed(2), 'MB')
